#!/usr/bin/env python3
"""Rebuild the records of the ai-capabilities-index frontier from Epoch AI's ECI scores.

Reads data/datasets/epoch-eci/eci_scores.csv and rewrites the `records` block of
data/frontiers/ai/ai-capabilities-index.yaml. Every other field is kept.

A model is a record when its score beats every model dated before it (ties on the same date
go to the higher score). Two series: all models, and open-weights models only.
"""
import csv
import sys
from pathlib import Path

import yaml

sys.path.insert(0, str(Path(__file__).resolve().parent))
from validate import load_yaml  # noqa: E402  (keeps dates as strings)

ROOT = Path(__file__).resolve().parent.parent
CSV_PATH = ROOT / "data" / "datasets" / "epoch-eci" / "eci_scores.csv"
FRONTIER_PATH = ROOT / "data" / "frontiers" / "ai" / "ai-capabilities-index.yaml"
SOURCE_ID = "epoch-eci"
SERIES = {
    "all-models": lambda r: True,
    "open-weights": lambda r: r["Accessibility group"] == "Open weights",
}


def read_rows():
    with open(CSV_PATH, encoding="utf-8-sig", newline="") as f:
        rows = [r for r in csv.DictReader(f) if r["eci"].strip() and r["date"].strip()]
    return sorted(rows, key=lambda r: (r["date"], -float(r["eci"]), r["Model"]))


def record(r, series):
    low, high = r["eci_ci_low"].strip(), r["eci_ci_high"].strip()
    interval = f"Epoch interval {low} to {high}" if low and high else "Epoch gives no interval for this model"
    parts = [interval, f"developer {r['Organization']}".strip(), r["Accessibility group"].lower()]
    return {
        "date": r["date"],
        "value": float(r["eci"]),
        "series": series,
        "holder": r["Display name"].strip() or r["Model"].strip(),
        "conditions": "; ".join(p for p in parts if p),
        "status": "confirmed",
        "source": SOURCE_ID,
    }


def main():
    rows = read_rows()
    records = []
    for series, keep in SERIES.items():
        best = None
        for r in rows:
            if not keep(r):
                continue
            value = float(r["eci"])
            if best is None or value > best:
                best = value
                records.append(record(r, series))

    data = load_yaml(FRONTIER_PATH)
    if SOURCE_ID not in {s["id"] for s in data["sources"]}:
        sys.exit(f"{FRONTIER_PATH} needs a source with id '{SOURCE_ID}'")
    data["records"] = records
    with open(FRONTIER_PATH, "w", encoding="utf-8") as f:
        f.write("# Records are generated by scripts/import_epoch_eci.py from data/datasets/epoch-eci/.\n")
        f.write("# Edit the other fields by hand; never edit the records directly.\n")
        yaml.safe_dump(data, f, sort_keys=False, allow_unicode=True, width=100)
    print(f"Wrote {len(records)} records to {FRONTIER_PATH.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
