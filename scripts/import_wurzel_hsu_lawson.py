#!/usr/bin/env python3
"""Rebuild the series and records of the fusion-performance frontier from the Wurzel & Hsu dataset.

Reads data/datasets/wurzel-hsu-lawson/results.csv and rewrites the `series` and `records`
blocks of data/frontiers/energy/fusion-performance.yaml. Every other field is kept.
A record is written for every achieved result with a triple product (paper Tables I-III).
Design projections (SPARC, ITER) and shots listed only in the Q_sci table (Table IV) are skipped;
the second group has no triple product in the source.
"""
import csv
import re
import sys
from pathlib import Path

import yaml

sys.path.insert(0, str(Path(__file__).resolve().parent))
from validate import load_yaml  # noqa: E402  (keeps dates as strings)

ROOT = Path(__file__).resolve().parent.parent
CSV_PATH = ROOT / "data" / "datasets" / "wurzel-hsu-lawson" / "results.csv"
FRONTIER_PATH = ROOT / "data" / "frontiers" / "energy" / "fusion-performance.yaml"
SOURCE_ID = "wurzel-hsu-2025"

# Grouped as the paper's data tables group them.
GROUPS = [
    ("Tokamaks (Table I)", ["Tokamak", "Spherical Tokamak"]),
    ("Other magnetic and lower-density magneto-inertial (Table II)",
     ["Stellarator", "Reverse Field Pinch", "Stabilized Pinch", "Spheromak", "Mirror", "Z Pinch",
      "Field Reversed Configuration", "Magnetized Target Fusion"]),
    ("Inertial and higher-density magneto-inertial (Table III)",
     ["Laser Direct Drive", "Laser Indirect Drive", "Magnetized Liner Inertial Fusion"]),
]
DEFINITIONS = {
    "n_i0 T_i0 tau_E*": "peak triple product n_i0·T_i0·τ_E*",
    "n <T_i>_n tau_stag": "n·⟨T_i⟩_n·τ_stag from stagnation pressure × burn duration",
}
FUEL = {
    "D-T": "D-T fuel (shown in the paper's plot of D-T experiments)",
    "D-D": "D-D fuel (the paper notes MagLIF on Z uses pure deuterium)",
    "": "fuel not stated per result in the source",
}


def slug(text):
    return re.sub(r"[^a-z0-9]+", "-", text.lower()).strip("-")


def conditions(row):
    parts = [DEFINITIONS[row["triple_product_definition"]], FUEL[row["fuel_stated"]],
             f"temperature is {row['temperature_kind']}"]
    if row["inferred"]:
        parts.append(row["inferred"])
    if row["q_sci"]:
        q = f"Q_sci on {row['q_sci_basis']} basis"
        if row["q_sci_comment"]:
            q += f" ({row['q_sci_comment'].strip()})"
        parts.append(q)
    return "; ".join(parts)


def main():
    with open(CSV_PATH, encoding="utf-8", newline="") as f:
        rows = [r for r in csv.DictReader(f)
                if r["triple_product_kev_m3_s"] and r["is_projection"] != "True"]

    concepts = {r["concept"] for r in rows}
    known = {c for _, cs in GROUPS for c in cs}
    if concepts - known:
        sys.exit(f"Unknown concepts in {CSV_PATH.name}: {sorted(concepts - known)}; add them to GROUPS")
    series = [{"id": slug(c), "label": c, "group": g} for g, cs in GROUPS for c in cs if c in concepts]

    records = []
    for r in sorted(rows, key=lambda r: (r["date"], int(r["wh_id"]))):
        extra = {"ion_temperature": float(r["temperature_kev"])}
        if r["q_sci"]:
            extra["q_sci"] = float(r["q_sci"])
        note = f"Wurzel & Hsu 2025, Table {r['paper_tables'].split()[0]}, shot {r['shot']}; dataset row {r['wh_id']}"
        if r["q_sci"] and float(r["q_sci"]) < 0.005:
            note += "; Table IV prints Q_sci as 0.00, the value here is the same ratio to two significant figures"
        records.append({
            "date": r["date"],
            "value": float(r["triple_product_kev_m3_s"]),
            "series": slug(r["concept"]),
            "holder": r["project"],
            "conditions": conditions(r),
            "status": "peer_reviewed",
            "source": SOURCE_ID,
            "note": note,
            "extra": extra,
        })

    data = load_yaml(FRONTIER_PATH)
    if SOURCE_ID not in {s["id"] for s in data["sources"]}:
        sys.exit(f"{FRONTIER_PATH} needs a source with id '{SOURCE_ID}'")
    data["series"] = series
    data["records"] = records

    with open(FRONTIER_PATH, "w", encoding="utf-8") as f:
        f.write("# Series and records are generated by scripts/import_wurzel_hsu_lawson.py.\n")
        f.write("# Edit the other fields by hand; edit the dataset, not the records, for record changes.\n")
        yaml.safe_dump(data, f, sort_keys=False, allow_unicode=True, width=100)
    print(f"Wrote {len(series)} series and {len(records)} records to {FRONTIER_PATH.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
