#!/usr/bin/env python3
"""Rebuild the series and records of the solar-cell-efficiency frontier from the NLR dataset.

Reads data/datasets/nlr-cell-efficiency/records.csv and rewrites the `series` and `records`
blocks of data/frontiers/energy/solar-cell-efficiency.yaml. Every other field is kept.
Rows NLR marks "(not on chart)" are skipped.
"""
import csv
import re
import sys
from pathlib import Path

import yaml

sys.path.insert(0, str(Path(__file__).resolve().parent))
from validate import load_yaml  # noqa: E402  (keeps dates as strings)

ROOT = Path(__file__).resolve().parent.parent
CSV_PATH = ROOT / "data" / "datasets" / "nlr-cell-efficiency" / "records.csv"
FRONTIER_PATH = ROOT / "data" / "frontiers" / "energy" / "solar-cell-efficiency.yaml"
SOURCE_ID = "nlr-data-table"

CLASS_ORDER = [
    "III-V Multijunction Cells",
    "Single-Junction GaAs",
    "Crystalline Si Cells",
    "Thin-Film Technologies",
    "Emerging PV",
    "Hybrid Tandems",
]
AREA_TYPES = {"da": "designated illumination area", "ap": "aperture area", "t": "total area"}


def slug(text):
    return re.sub(r"[^a-z0-9]+", "-", text.lower()).strip("-")


def conditions(row):
    parts = []
    if row["description"].strip():
        parts.append(row["description"].strip())
    if row["area_cm2"]:
        area_type = AREA_TYPES.get(row["area_type"].strip().lower(), row["area_type"].strip())
        parts.append(f"{row['area_cm2']} cm² {area_type}".strip())
    if row["suns"] and row["suns"] != "1":
        parts.append(f"{row['suns']} suns")
    if row["uncertainty_pct"]:
        parts.append(f"uncertainty ±{row['uncertainty_pct']}%")
    if row["test_center"].strip() and row["test_center"].strip().lower() != "unknown":
        parts.append(f"measured by {row['test_center'].strip()}")
    return "; ".join(parts)


def main():
    with open(CSV_PATH, encoding="utf-8", newline="") as f:
        rows = [r for r in csv.DictReader(f) if r["cell_type"].strip() != "(not on chart)"]

    series, seen = [], set()
    for cls in CLASS_ORDER + sorted({r["material_class"] for r in rows} - set(CLASS_ORDER)):
        for cell in sorted({r["cell_type"].strip() for r in rows if r["material_class"] == cls}):
            sid = slug(f"{cls} {cell}")
            if sid not in seen:
                seen.add(sid)
                series.append({"id": sid, "label": cell, "group": cls})

    records = []
    for r in sorted(rows, key=lambda r: (r["measurement_date"], r["record_id"])):
        rec = {
            "date": r["measurement_date"],
            "value": float(r["efficiency_pct"]),
            "series": slug(f"{r['material_class']} {r['cell_type'].strip()}"),
            "holder": r["groups"].strip() or "Not listed",
        }
        cond = conditions(r)
        if cond:
            rec["conditions"] = cond
        rec["status"] = "confirmed"
        rec["source"] = SOURCE_ID
        rec["note"] = f"NLR record {r['record_id']}"
        records.append(rec)

    data = load_yaml(FRONTIER_PATH)
    if SOURCE_ID not in {s["id"] for s in data["sources"]}:
        sys.exit(f"{FRONTIER_PATH} needs a source with id '{SOURCE_ID}'")
    data["series"] = series
    data["records"] = records

    with open(FRONTIER_PATH, "w", encoding="utf-8") as f:
        f.write("# Series and records are generated by scripts/import_nlr_cell_efficiency.py.\n")
        f.write("# Edit the other fields by hand; edit the dataset, not the records, for record changes.\n")
        yaml.safe_dump(data, f, sort_keys=False, allow_unicode=True, width=100)
    print(f"Wrote {len(series)} series and {len(records)} records to {FRONTIER_PATH.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
