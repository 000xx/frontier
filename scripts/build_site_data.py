"""Build site/js/data.js from the data files in this repository.

Usage: python scripts/build_site_data.py

Every file under data/frontiers/ becomes a page on the site. Site-level choices
that are not data (which series to feature, what is next in the queue) live in
site/config.json. The output is generated: do not edit it or commit it.
"""
import json
import re
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parent.parent
OUT = ROOT / "site" / "js" / "data.js"


def one_line(text):
    return " ".join(str(text or "").split())


def dataset_notice(sources):
    """Return (credit line, notice text) from the primary dataset's NOTICE.md, if any."""
    for s in sources:
        m = re.search(r"data/datasets/([\w-]+)/NOTICE\.md", s.get("notes") or "")
        path = ROOT / "data" / "datasets" / m.group(1) / "NOTICE.md" if m else None
        if path and path.exists():
            text = path.read_text(encoding="utf-8")
            quoted = [line[2:] for line in text.split("\n") if line.startswith("> ")]
            credit = re.search(r'carry the line "([^"]+)"', text)
            return (credit.group(1) if credit else ""), "\n".join(quoted).strip()
    return "", ""


def build():
    domains = yaml.safe_load((ROOT / "data" / "domains.yaml").read_text(encoding="utf-8"))
    domain_name = {d["id"]: d["name"] for d in domains}
    config = json.loads((ROOT / "site" / "config.json").read_text(encoding="utf-8"))

    frontiers = []
    for path in sorted((ROOT / "data" / "frontiers").rglob("*.yaml")):
        d = yaml.safe_load(path.read_text(encoding="utf-8"))
        records = {}
        for r in d.get("records") or []:
            if r.get("value") is None or not r.get("series"):
                continue
            records.setdefault(r["series"], []).append([
                str(r["date"]), r["value"], r.get("holder") or "", r.get("conditions") or "",
                r.get("status") or "", r.get("source") or "",
            ])
        for rows in records.values():
            rows.sort(key=lambda row: row[0])
        sources = d.get("sources") or []
        credit, notice = dataset_notice(sources)
        metric = d.get("metric") or {}
        frontiers.append({
            "id": d["id"],
            "title": d["title"],
            "domain": domain_name.get(d.get("domain"), d.get("domain", "")),
            "subfield": d.get("subfield", ""),
            "dataStatus": d.get("status", ""),
            "summary": one_line(d.get("summary")),
            "unit": metric.get("unit", ""),
            "explainer": one_line(metric.get("explainer")),
            "shape": str((d.get("chart") or {}).get("primary", "")).replace("-", " ").capitalize(),
            "series": d.get("series") or [],
            "records": records,
            "featured": (config.get("featured") or {}).get(d["id"]),
            "sources": [{"id": s["id"], "name": s["name"], "url": s.get("url"), "kind": s.get("kind")} for s in sources],
            "events": [{"date": str(e["date"]), "title": e["title"], "why": one_line(e.get("why_it_matters")), "url": e.get("url")}
                       for e in d.get("events") or []],
            "lastChecked": str((d.get("update") or {}).get("last_checked", "")),
            "credit": credit,
            "notice": notice,
        })

    data = {
        "site": {"name": config.get("name", "Frontier in Numbers")},
        "domains": [d["name"] for d in domains],
        "planned": config.get("planned") or [],
        "frontiers": frontiers,
    }
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text(
        "/* Generated by scripts/build_site_data.py. Do not edit by hand. */\n"
        "window.FRONTIER_DATA = " + json.dumps(data, ensure_ascii=False, separators=(",", ":")) + ";\n",
        encoding="utf-8",
    )
    total = sum(len(rows) for f in frontiers for rows in f["records"].values())
    print(f"Wrote {OUT.relative_to(ROOT)}: {len(frontiers)} frontiers, {total} records, {len(domains)} domains")


if __name__ == "__main__":
    build()
